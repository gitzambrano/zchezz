#!/usr/bin/env python3
"""Train and export auxiliary linear NNUE head for fast evaluation.

Fits a linear head on accumulator/hidden activations of the selected profile
using positions from a specified training dataset.
Emits a C header with fixed-point weights.
"""
from __future__ import annotations

import argparse
import glob
import sys
from pathlib import Path
from typing import Optional

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "utils"))
sys.path.insert(0, str(ROOT / "train"))

from engine_profiles import DEFAULT_PROFILE, profile


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--profile", default=DEFAULT_PROFILE, help=f"Engine profile (default: {DEFAULT_PROFILE})")
    parser.add_argument(
        "--dataset",
        default="data/lichess_cp_sf400k_filter",
        help="Training dataset directory containing parquet files",
    )
    parser.add_argument("--alpha", type=float, default=1.0, help="Ridge regression regularization alpha")
    parser.add_argument("--output", default="", help="Output header path (default: inside engine profile dir)")
    parser.add_argument("--show-config", action="store_true", help="Print configuration and exit")

    args = parser.parse_args()

    prof = profile(args.profile)
    dataset_path = ROOT / args.dataset
    out_path = Path(args.output) if args.output else (prof.engine_dir / "fast_head_weights.h")

    if args.show_config:
        print("Auxiliary Head Training Configuration:")
        print(f"  profile      = {prof.name}")
        print(f"  dataset_path = {dataset_path}")
        print(f"  alpha        = {args.alpha}")
        print(f"  output_path  = {out_path}")
        return 0

    if not dataset_path.is_dir():
        print(f"Error: Dataset directory not found: {dataset_path}")
        return 1

    parquets = sorted(dataset_path.glob("*.parquet"))
    if not parquets:
        print(f"Error: No parquet files found in {dataset_path}")
        return 1

    print(f"Starting auxiliary head training for profile {prof.name} using {len(parquets)} parquet files...")
    # Dynamic imports for heavy libraries only when executing
    import numpy as np
    import pandas as pd
    from sklearn.linear_model import Ridge
    import torch
    from encoding_nnu3 import encode_chunk
    from model_nnu3 import NNUE

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    net = NNUE().to(device)
    if prof.weights.is_file():
        from import_nnu3 import import_nnu3
        import_nnu3(prof.weights, net)
    net.eval()

    all_fens = []
    all_cp = []
    for p in parquets:
        df = pd.read_parquet(p)
        all_fens.extend(df["fen"].tolist())
        all_cp.extend(df["cp"].tolist())

    print(f"Loaded {len(all_fens):,} positions. Encoding activations...")
    batch_size = 8192
    hidden_features = []

    with torch.no_grad():
        for i in range(0, len(all_fens), batch_size):
            chunk_fens = all_fens[i : i + batch_size]
            stm_indices, opp_indices, count = encode_chunk(chunk_fens)
            stm_t = torch.from_numpy(stm_indices[:count]).to(device)
            opp_t = torch.from_numpy(opp_indices[:count]).to(device)
            acc_stm = net.ft(stm_t)
            acc_opp = net.ft(opp_t)
            h = torch.clamp(torch.cat([acc_stm, acc_opp], dim=1), 0.0, 1.0)
            hidden_features.append(h.cpu().numpy())

    X = np.vstack(hidden_features)
    y = np.array(all_cp, dtype=np.float32)

    print(f"Fitting Ridge regression on shape {X.shape}...")
    reg = Ridge(alpha=args.alpha, fit_intercept=True)
    reg.fit(X, y)

    coef = reg.coef_
    intercept = reg.intercept_
    scale = 320.0 / 4096.0

    lines = [
        "/* Auto-generated by train/train_aux_head.py */",
        "#ifndef FAST_HEAD_WEIGHTS_H",
        "#define FAST_HEAD_WEIGHTS_H",
        "",
        f"static const float FAST_HEAD_INTERCEPT = {intercept:.4f}f;",
        f"static const float FAST_HEAD_SCALE = {scale:.8f}f;",
        f"static const float FAST_HEAD_WEIGHTS[{len(coef)}] = {{",
    ]
    for i in range(0, len(coef), 8):
        chunk = ", ".join(f"{v:.4f}f" for v in coef[i : i + 8])
        lines.append(f"    {chunk},")
    lines.extend(["};", "", "#endif /* FAST_HEAD_WEIGHTS_H */", ""])

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Successfully exported fast head weights to {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
